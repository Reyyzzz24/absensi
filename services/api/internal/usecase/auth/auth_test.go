// D-24: logout revokes only the specific refresh token presented, not every
// token for that employee/session family.
func TestRefresh_RejectsTokenAfterLogout(t *testing.T) {
	svc := newService(t)
	ctx := context.Background()

	issuer := authtoken.NewIssuer("test-secret")
	refreshA, err := issuer.Generate("1", authtoken.AudienceEmployee, "", time.Hour)
	if err != nil {
		t.Fatalf("generate token A: %v", err)
	}
	refreshB, err := issuer.Generate("1", authtoken.AudienceEmployee, "", time.Hour)
	if err != nil {
		t.Fatalf("generate token B: %v", err)
	}

	if err := svc.Logout(ctx, refreshA); err != nil {
		t.Fatalf("logout: %v", err)
	}

	if _, err := svc.Refresh(ctx, refreshA); !errors.Is(err, auth.ErrInvalidCredentials) {
		t.Fatalf("expected revoked token A to be rejected, got %v", err)
	}
	if _, err := svc.Refresh(ctx, refreshB); err != nil {
		t.Fatalf("expected unrelated token B to remain valid, got %v", err)
	}
}

func TestLogout_IsIdempotentAndToleratesGarbageInput(t *testing.T) {
	svc := newService(t)
	ctx := context.Background()

	issuer := authtoken.NewIssuer("test-secret")
	refresh, err := issuer.Generate("1", authtoken.AudienceEmployee, "", time.Hour)
	if err != nil {
		t.Fatalf("generate token: %v", err)
	}

	if err := svc.Logout(ctx, refresh); err != nil {
		t.Fatalf("first logout: %v", err)
	}
	if err := svc.Logout(ctx, refresh); err != nil {
		t.Fatalf("second logout with the same token must not error: %v", err)
	}
	if err := svc.Logout(ctx, "not-a-real-jwt"); err != nil {
		t.Fatalf("logout with garbage input must not error: %v", err)
	}
}
