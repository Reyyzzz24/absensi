func newService(t *testing.T) auth.Service {
	t.Helper()
	gdb := testutil.NewDB(t)
	issuer := authtoken.NewIssuer("test-secret")
	return auth.NewService(
		repo.NewEmployeeRepo(gdb),
		repo.NewUserRepo(gdb),
		issuer,
		repo.NewRevokedTokenRepo(gdb),
		15*time.Minute,
		30*24*time.Hour,
	)
}

// D-12/CLAUDE.md §8: bcrypt hashes generated by the legacy Laravel system
// must verify correctly here with no migration/rehash step. bcrypt.
// GenerateFromPassword stands in for "a hash minted by some other bcrypt
// implementation" -- the point under test is that our verify path
// (bcrypt.CompareHashAndPassword) works on any valid bcrypt hash, not one
// generated by our own code specifically.
func TestLoginEmployee_AcceptsPreexistingBcryptHash(t *testing.T) {
	gdb := testutil.NewDB(t)
	hash, err := bcrypt.GenerateFromPassword([]byte("legacy-password"), bcrypt.DefaultCost)
	if err != nil {
		t.Fatalf("generate hash: %v", err)
	}
	if err := gdb.Create(&domain.Employee{NIK: "0001", FullName: "Legacy", PasswordHash: string(hash), IsActive: true}).Error; err != nil {
		t.Fatalf("seed employee: %v", err)
	}

	issuer := authtoken.NewIssuer("test-secret")
	svc := auth.NewService(repo.NewEmployeeRepo(gdb), repo.NewUserRepo(gdb), issuer, repo.NewRevokedTokenRepo(gdb), 15*time.Minute, 30*24*time.Hour)

	tokens, emp, err := svc.LoginEmployee(context.Background(), "0001", "legacy-password")
	if err != nil {
		t.Fatalf("expected login to succeed against a pre-existing bcrypt hash, got %v", err)
	}
	if emp.NIK != "0001" || tokens.AccessToken == "" {
		t.Fatalf("expected valid session, got emp=%+v tokens=%+v", emp, tokens)
	}
}

